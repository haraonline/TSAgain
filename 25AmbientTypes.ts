// What are Ambient types ?
// Ambient types in TypeScript are type declarations that 
// describe the shape of existing JavaScript code. 
// They allow TypeScript to understand the types of variables,
// functions, and objects that are defined outside of the TypeScript
// codebase, such as in third-party libraries or global variables. 
// Ambient types are typically defined in .d.ts files and provide 
// type information without generating any JavaScript code. 
// This enables developers to use JavaScript libraries with TypeScript 
// while benefiting from type checking and IntelliSense features.